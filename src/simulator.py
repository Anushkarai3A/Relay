
import random
import threading
import time
from typing import Generator, Optional


class SimulatedModelService:
    """
    Local stand-in model service.

    Simulates:
    - Initial response latency
    - Random latency variation
    - Streaming text responses
    - Random service failures
    - Increased latency under concurrent load
    """

    def __init__(
        self,
        base_latency_ms: int = 350,
        latency_jitter_ms: int = 100,
        failure_rate: float = 0.05,
        overload_threshold: int = 5,
        overload_slowdown_ms: int = 250,
        chunk_size: int = 12,
        seed: Optional[int] = None
    ):

        if base_latency_ms < 0:
            raise ValueError("Base latency cannot be negative.")

        if latency_jitter_ms < 0:
            raise ValueError("Latency jitter cannot be negative.")

        if not 0 <= failure_rate <= 1:
            raise ValueError("Failure rate must be between 0 and 1.")

        if overload_threshold < 1:
            raise ValueError("Overload threshold must be at least 1.")

        if overload_slowdown_ms < 0:
            raise ValueError("Overload slowdown cannot be negative.")

        if chunk_size < 1:
            raise ValueError("Chunk size must be at least 1.")

        self.base_latency_ms = base_latency_ms
        self.latency_jitter_ms = latency_jitter_ms
        self.failure_rate = failure_rate
        self.overload_threshold = overload_threshold
        self.overload_slowdown_ms = overload_slowdown_ms
        self.chunk_size = chunk_size

        self.random = random.Random(seed)

        self.lock = threading.Lock()

        self.in_flight = 0
        self.total_requests = 0
        self.successful_requests = 0
        self.failed_requests = 0

    # ======================================
    # REQUEST COUNTERS
    # ======================================

    def _start_request(self):

        with self.lock:

            self.in_flight += 1
            self.total_requests += 1

            current_in_flight = self.in_flight

        return current_in_flight

    def _finish_request(self, success):

        with self.lock:

            self.in_flight -= 1

            if success:
                self.successful_requests += 1
            else:
                self.failed_requests += 1

    # ======================================
    # SIMULATE SERVICE LATENCY
    # ======================================

    def calculate_latency(self, concurrent_requests):

        jitter = self.random.uniform(
            0,
            self.latency_jitter_ms
        )

        overload_requests = max(
            0,
            concurrent_requests - self.overload_threshold
        )

        overload_delay = (
            overload_requests * self.overload_slowdown_ms
        )

        total_latency = (
            self.base_latency_ms
            + jitter
            + overload_delay
        )

        return round(total_latency, 2)

    # ======================================
    # GENERATE STREAMING RESPONSE
    # ======================================

    def generate_stream(
        self,
        prompt: str,
        request_id: Optional[str] = None
    ) -> Generator[str, None, None]:

        request_id = request_id or "unknown"

        concurrent_requests = self._start_request()

        success = False

        try:

            # Calculate simulated latency.
            latency_ms = self.calculate_latency(
                concurrent_requests
            )

            # Simulate time until the first token.
            time.sleep(latency_ms / 1000)

            # Simulate random service failure.
            if self.random.random() < self.failure_rate:

                raise RuntimeError(
                    f"Simulated service failure for request {request_id}"
                )

            response = (
                f"This is a simulated research assistant response "
                f"for request {request_id}. "
                f"The system received the prompt: {prompt}. "
                f"This response is generated by the local stand-in "
                f"service and does not come from a real language model."
            )

            # Stream the response in small chunks.
            for start in range(
                0,
                len(response),
                self.chunk_size
            ):

                chunk = response[
                    start:start + self.chunk_size
                ]

                yield chunk

                # Simulate a small delay between streamed chunks.
                time.sleep(0.02)

            success = True

        finally:

            self._finish_request(success)

    # ======================================
    # SERVICE STATUS
    # ======================================

    def get_stats(self):

        with self.lock:

            return {
                "total_requests": self.total_requests,
                "successful_requests": self.successful_requests,
                "failed_requests": self.failed_requests,
                "in_flight": self.in_flight,
                "base_latency_ms": self.base_latency_ms,
                "failure_rate": self.failure_rate,
                "overload_threshold": self.overload_threshold,
                "overload_slowdown_ms": self.overload_slowdown_ms
            }


