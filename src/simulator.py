if __name__ == "__main__":

    service = SimulatedModelService(
        base_latency_ms=350,
        latency_jitter_ms=100,
        failure_rate=0.0,
        overload_threshold=3,
        overload_slowdown_ms=250,
        seed=42
    )

    print("=" * 60)
    print("THE RELAY - SIMULATED MODEL SERVICE")
    print("=" * 60)

    request_id = "SIM-001"

    start = time.perf_counter()

    first_token_ms = None
    response_parts = []

    try:

        for chunk in service.generate_stream(
            prompt="Explain the Transformer attention mechanism.",
            request_id=request_id
        ):

            if first_token_ms is None:

                first_token_ms = (
                    time.perf_counter() - start
                ) * 1000

            response_parts.append(chunk)

        total_ms = (
            time.perf_counter() - start
        ) * 1000

        print("\nResponse:")
        print("".join(response_parts))

        print("\nRequest metrics:")
        print(f"First token: {first_token_ms:.2f} ms")
        print(f"Total time: {total_ms:.2f} ms")

    except RuntimeError as error:

        print("\nRequest failed:")
        print(error)

    print("\nService statistics:")
    print(service.get_stats())
